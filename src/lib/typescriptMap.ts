import type { SchemaRuntimeData } from "./fieldMap.ts";

const editBoundaryLine = "-".repeat(100);
const editBoundaryPattern = new RegExp(`^// ${editBoundaryLine}$`, "m");

export function renderClientConfig(schemaSourceDescription: string, endpoint: string | undefined): string {
  const endpointSource = endpoint === undefined ? "undefined" : JSON.stringify(endpoint);

  return [
    "const clientConfig: ClientConfig = {",
    `\tendpoint: ${endpointSource},`,
    "\theaders: {",
    '\t\t// "authorization": "Bearer token",',
    "\t},",
    "};",
    "",
    `// ${editBoundaryLine}`,
    `// Generated by graphql-isoclient from ${schemaSourceDescription}.`,
    "// Do not edit below this line.",
    `// ${editBoundaryLine}`,
  ].join("\n");
}

export function renderRuntimeDataLiterals(runtimeData: SchemaRuntimeData): string {
  return [
    "type RuntimeFieldEntry = {",
    "\tselect?: string;",
    "\targuments?: Record<string, string>;",
    "};",
    "",
    "type RuntimeFieldMap = Record<string, RuntimeFieldEntry>;",
    "",
    "type RuntimeScalarFieldLists = Record<string, string[]>;",
    "",
    "const runtimeData = {",
    "\tdefaultEndpoint: clientConfig.endpoint,",
    "\tdefaultHeaders: clientConfig.headers,",
    `\tfieldMap: ${indentSourceLiteral(JSON.stringify(runtimeData.fieldMap, null, "\t"))},`,
    `\tscalarFieldLists: ${indentSourceLiteral(JSON.stringify(runtimeData.scalarFieldLists, null, "\t"))},`,
    "};",
  ].join("\n");
}

export function assembleGeneratedFile(parts: GeneratedFileParts): string {
  return (
    [parts.clientConfig, parts.runtimeDataLiterals, parts.operationExports, parts.runtimeSections, parts.typeSurface]
      .filter((part) => part.trim().length > 0)
      .join("\n\n") + "\n"
  );
}

export function preserveExistingConfiguration(existingFileText: string | undefined, generatedFileText: string): PreservedFileResult {
  if (existingFileText === undefined) {
    return { configurationPreserved: false, fileText: generatedFileText };
  }

  const existingBoundaryIndex = findEditBoundaryIndex(existingFileText);
  const generatedBoundaryIndex = findEditBoundaryIndex(generatedFileText);

  if (existingBoundaryIndex === -1 || generatedBoundaryIndex === -1) {
    return { configurationPreserved: false, fileText: generatedFileText };
  }

  return {
    configurationPreserved: true,
    fileText: existingFileText.slice(0, existingBoundaryIndex) + generatedFileText.slice(generatedBoundaryIndex),
  };
}

function findEditBoundaryIndex(fileText: string): number {
  const boundaryMatch = editBoundaryPattern.exec(fileText);

  return boundaryMatch?.index ?? -1;
}

function indentSourceLiteral(sourceLiteral: string): string {
  return sourceLiteral
    .split("\n")
    .map((sourceLine, lineIndex) => (lineIndex === 0 ? sourceLine : `\t${sourceLine}`))
    .join("\n");
}

export type GeneratedFileParts = {
  clientConfig: string;
  runtimeDataLiterals: string;
  typeSurface: string;
  runtimeSections: string;
  operationExports: string;
};

export type GeneratedTypeSurfaceParts = {
  argumentTypes: string;
  enumTypes: string;
  fieldArgumentTypes: string;
  inputObjectTypes: string;
  operationTypes: string;
  requestTypes: string;
  responseTypes: string;
  resultTypes: string;
};

export type PreservedFileResult = {
  configurationPreserved: boolean;
  fileText: string;
};
