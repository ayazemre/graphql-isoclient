import type { SchemaRuntimeData } from "./fieldMap.ts";
import type { RootTypeNames } from "./schema.ts";
import type { SchemaModel } from "./schemaModel.ts";

export function renderGeneratedFileHeader(schemaSourceDescription: string): string {
  return `// Generated by graphql-isoclient from ${schemaSourceDescription}. Do not edit this file.`;
}

export function renderRuntimeDataLiterals(runtimeData: SchemaRuntimeData, defaultEndpoint: string | undefined): string {
  return [
    "type RuntimeFieldEntry = {",
    "\tselect?: string;",
    "\targuments?: Record<string, string>;",
    "};",
    "",
    "type RuntimeFieldMap = Record<string, RuntimeFieldEntry>;",
    "",
    "type RuntimeScalarFieldLists = Record<string, string[]>;",
    "",
    "const runtimeData = {",
    `\tfieldMap: ${indentSourceLiteral(JSON.stringify(runtimeData.fieldMap, null, "\t"))},`,
    `\tscalarFieldLists: ${indentSourceLiteral(JSON.stringify(runtimeData.scalarFieldLists, null, "\t"))},`,
    `\tdefaultEndpoint: ${JSON.stringify(defaultEndpoint)},`,
    "};",
  ].join("\n");
}

export function renderOperationExports(rootTypeNames: RootTypeNames): string {
  const operationExports = [
    [
      "export function query(selection: SelectionMap, options?: RequestOptions): Promise<unknown> {",
      `\treturn runOperation("query", ${JSON.stringify(rootTypeNames.query)}, selection, runtimeData, options);`,
      "}",
    ].join("\n"),
  ];

  if (rootTypeNames.mutation !== undefined) {
    operationExports.push(
      [
        "export function mutation(selection: SelectionMap, options?: RequestOptions): Promise<unknown> {",
        `\treturn runOperation("mutation", ${JSON.stringify(rootTypeNames.mutation)}, selection, runtimeData, options);`,
        "}",
      ].join("\n"),
    );
  }

  if (rootTypeNames.subscription !== undefined) {
    operationExports.push(
      [
        "export function subscription(selection: SelectionMap, options: SubscriptionRequestOptions): AsyncIterableIterator<unknown> {",
        `\treturn runOperation("subscription", ${JSON.stringify(rootTypeNames.subscription)}, selection, runtimeData, options);`,
        "}",
      ].join("\n"),
    );
  }

  operationExports.push("export { createIsoclientError, isIsoclientError };");

  return operationExports.join("\n\n");
}

export function assembleGeneratedFile(parts: GeneratedFileParts): string {
  return (
    [parts.fileHeader, parts.runtimeDataLiterals, parts.typeSurface, parts.runtimeSections, parts.operationExports]
      .filter((part) => part.trim().length > 0)
      .join("\n\n") + "\n"
  );
}

